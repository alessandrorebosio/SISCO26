package it.unibo.sisco.view.impl.panel;

import java.awt.BorderLayout;
import java.util.List;
import java.util.function.Consumer;

import javax.swing.JPanel;

import it.unibo.sisco.controller.api.Configuration;
import it.unibo.sisco.controller.api.SimulationEvents;

/**
 * Main panel shown while the simulation is running.
 */
public final class SimulationPanel extends JPanel {

    private static final long serialVersionUID = 1L;

    private final DrawPanel drawPanel;
    private final OptionPanel optionPanel;

    /**
     * Creates the simulation panel with an options sidebar and drawing area.
     *
     * @param configuration selected simulation configuration
     * @param eventHandler handles events generated by the options panel
     */
    public SimulationPanel(final Configuration configuration, final Consumer<SimulationEvents> eventHandler) {
        super(new BorderLayout());
        this.drawPanel = new DrawPanel();
        this.optionPanel = new OptionPanel(configuration, eventHandler);

        this.add(this.optionPanel, BorderLayout.WEST);
        this.add(this.drawPanel, BorderLayout.CENTER);
    }

    /**
     * Returns the panel that draws the simulation.
     *
     * @return the drawing panel
     */
    public DrawPanel getDrawPanel() {
        return this.drawPanel;
    }

    /**
     * Updates the displayed bodies and the options panel statistics.
     *
     * @param shapes the current body shapes
     * @param elapsedTime elapsed time in milliseconds
     * @param virtualTime the current virtual time
     * @param iteration the number of completed steps
     * @param stepsPerSecond simulation steps per second of computation time
     */
    public void display(final List<BodyShape> shapes, final long elapsedTime, final double virtualTime, final long iteration, final int stepsPerSecond) {
        this.drawPanel.display(shapes);
        this.optionPanel.updateStatistics(elapsedTime, virtualTime, iteration, stepsPerSecond);
        this.drawPanel.repaint();
    }

    /**
     * Shows the completion status in the options panel.
     *
     * @param elapsedMillis elapsed wall-clock time in milliseconds
     */
    public void showSimulationOver(final long elapsedMillis) {
        this.optionPanel.showSimulationOver(elapsedMillis);
    }
}
